import { expect, test } from '@playwright/test'
import { openDemo } from './open-demo'

test('the sorted, horizontal bar chart keeps its data and keyboard readout accessible', async ({ page }) => {
  await openDemo(page, 'bar-chart')
  const chart = page.getByRole('region', { name: 'Illustrative revenue by region' })
  await page.getByRole('tab', { name: 'Horizontal', exact: true }).click()
  await page.getByRole('button', { name: 'Sort by total' }).click()
  const inspector = chart.getByRole('slider')
  await inspector.focus()
  await inspector.press('Home')
  await expect(inspector).toHaveAttribute('aria-valuetext', 'Europe. Subscriptions $102K. Services $61K. Marketplace $36K')
  await expect(chart.getByRole('table')).toHaveAccessibleName('Illustrative revenue by region data')
  const series = chart.getByRole('button', { name: 'Subscriptions' })
  await series.click()
  await expect(series).toHaveAttribute('aria-pressed', 'false')
})

test('donut legend selection and sparklines can be inspected without a mouse', async ({ page }) => {
  await openDemo(page, 'donut-chart')
  const slice = page.getByRole('button', { name: /^Business/ })
  await slice.focus()
  await slice.press('Enter')
  await expect(slice).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByText('Filtering by Business')).toBeVisible()
  await openDemo(page, 'sparkline')
  const inspector = page.getByRole('slider', { name: 'Active users, last 30 days: inspect samples' })
  await inspector.focus()
  await inspector.press('Home')
  await expect(inspector).toHaveAttribute('aria-valuetext', 'Sep 1: 1,724')
  await page.getByRole('button', { name: 'Add sample' }).click()
  await inspector.press('Home')
  await expect(inspector).toHaveAttribute('aria-valuetext', /^Sep 2:/)
})

test('calendar ranges support keyboard anchoring, extension and dismissal', async ({ page }) => {
  await openDemo(page, 'returns-calendar')
  const january = page.getByRole('button', { name: 'Jan 2021 +1.1%' })
  await january.focus()
  await january.press('Enter')
  await expect(january).toHaveAttribute('aria-pressed', 'true')
  await january.press('Tab')
  const february = page.getByRole('button', { name: /^Feb 2021 / })
  await expect(february).toBeFocused()
  await february.press('Enter')
  await expect(page.getByRole('tooltip')).toHaveAccessibleName('Jan 2021 – Feb 2021 +5.1% 2 months')
  await february.press('Escape')
  await expect(january).toHaveAttribute('aria-pressed', 'false')
})
