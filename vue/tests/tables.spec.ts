import { expect, test } from '@playwright/test'
import { openDemo } from './open-demo'

test('sorts, selects by stable id, resizes, reorders and virtualizes 10,000 rows', async ({ page }) => {
  await openDemo(page, 'table')
  const table = page.getByRole('table', { name: 'People' })
  await expect(table).toHaveAttribute('aria-rowcount', '10001')
  expect(await table.getByRole('row').count()).toBeLessThan(35)
  const sort = table.getByRole('button', { name: 'MRR', exact: true })
  await expect(sort.locator('..').locator('..')).toHaveAttribute('aria-sort', 'descending')
  await table.getByLabel('Select row 1', { exact: true }).check()
  await expect(page.getByText('· 1 selected', { exact: true })).toBeVisible()
  await sort.click()
  await sort.click()
  await expect(sort.locator('..').locator('..')).toHaveAttribute('aria-sort', 'ascending')
  await expect(table.getByLabel('Select row 1', { exact: true })).not.toBeChecked()
  await table.getByLabel('Select all rows').check()
  await expect(page.getByText('· 10,000 selected', { exact: true })).toBeVisible()
  const nameHeader = table.locator('th[data-key="name"]')
  const before = await nameHeader.evaluate(element => element.getBoundingClientRect().width)
  await table.getByRole('button', { name: 'Resize name column' }).press('ArrowRight')
  expect(await nameHeader.evaluate(element => element.getBoundingClientRect().width)).toBeGreaterThan(before + 10)
  await table.getByRole('button', { name: 'Reorder name column' }).press('ArrowRight')
  await expect(table.locator('th[data-key]').first()).toHaveAttribute('data-key', 'role')
  await page.getByRole('region', { name: 'People' }).evaluate(element => { element.scrollTop = element.scrollHeight })
  await expect(table.getByLabel('Select row 10000', { exact: true })).toBeChecked()
})

test('edits a cell and column name, inserts a row and removes a column', async ({ page }) => {
  await openDemo(page, 'table-editable')
  const table = page.getByRole('table', { name: 'Team editor' })
  await table.getByRole('textbox', { name: 'name for row 1', exact: true }).fill('River Park')
  await table.getByRole('textbox', { name: 'Rename name column' }).fill('Member name')
  await table.getByRole('button', { name: 'Row 1 options' }).click()
  await page.getByRole('menuitem', { name: 'Insert after' }).click()
  await expect(table).toHaveAttribute('aria-rowcount', '6')
  await table.getByRole('button', { name: 'team column options' }).click()
  await page.getByRole('menuitem', { name: 'Delete column' }).click()
  await expect(table.getByRole('textbox', { name: 'Rename team column' })).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Editable' }).uncheck()
  await expect(table.getByRole('cell', { name: 'River Park' })).toBeVisible()
  await expect(table.getByRole('columnheader', { name: 'Member name' })).toBeVisible()
})

test('asynchronous table appends one local page when approaching the end', async ({ page }) => {
  await openDemo(page, 'table-async')
  const region = page.getByRole('region', { name: 'Paged people' })
  await expect(page.getByRole('status').filter({ hasText: '20 loaded' })).toBeVisible()
  await region.evaluate(element => { element.scrollTop = element.scrollHeight })
  await expect(page.getByRole('status').filter({ hasText: '40 loaded' })).toBeVisible()
  await expect(region.getByRole('table')).toHaveAttribute('aria-rowcount', '41')
})
